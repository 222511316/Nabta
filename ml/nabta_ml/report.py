"""Writes ml/reports/evaluation.md and the confusion matrix image from evaluation.json's data."""

import numpy as np

from nabta_ml import config

LABELS = {
    "bioclip": "BioCLIP + trained head",
    "resnet50": "ResNet-50 + trained head",
}


def pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def confusion_image(confusion: list[list[int]], names: list[str], title: str, path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    matrix = np.array(confusion, dtype=float)
    share = matrix / np.clip(matrix.sum(axis=1, keepdims=True), 1, None)  # each row: where that category went
    figure, axes = plt.subplots(figsize=(8.5, 7.2), dpi=150)
    axes.imshow(share, cmap="Greens", vmin=0, vmax=1)
    axes.set_xticks(range(len(names)), names, rotation=35, ha="right")
    axes.set_yticks(range(len(names)), names)
    axes.set_xlabel("Predicted category")
    axes.set_ylabel("True category")
    axes.set_title(title)
    for i in range(len(names)):
        for j in range(len(names)):
            if matrix[i, j]:
                colour = "white" if share[i, j] > 0.6 else "#17261c"
                axes.text(j, i, int(matrix[i, j]), ha="center", va="center", fontsize=8, color=colour)
    figure.tight_layout()
    figure.savefig(path)
    plt.close(figure)


def write_report(summary: dict, names: list[str]) -> None:
    models = summary["models"]
    chosen = models[summary["chosen"]]
    baseline = models.get(summary["baseline"]) if summary["baseline"] else None
    counts = summary["counts"]
    lines = []
    add = lines.append

    add("# Nabta pest model: evaluation\n")
    add(
        f"Generated by `python -m nabta_ml.train` on {summary['date']}. Every number below is on the fixed "
        "IP102 test split of Nabta's eight categories, with near-duplicates of training and validation "
        "images removed (see [audit.md](audit.md)). Choices were made on the validation split only.\n"
    )

    add("## Result\n")
    add("| Model | Validation macro F1 | Test macro F1 | Test accuracy |")
    add("| --- | ---: | ---: | ---: |")
    for name, result in models.items():
        label = LABELS[name] + (" (chosen)" if name == summary["chosen"] else "")
        label += " (baseline)" if name == summary["baseline"] else ""
        add(
            f"| {label} | {result['validation_macro_f1']:.3f} | {result['test']['macro_f1']:.3f} "
            f"| {pct(result['test']['accuracy'])} |"
        )
    if summary["zero_shot"]:
        zero = summary["zero_shot"]["test"]
        add(f"| BioCLIP zero-shot, no training | – | {zero['macro_f1']:.3f} | {pct(zero['accuracy'])} |")
    official = summary["official_ip102_baseline"]
    if official:
        for reading, scope in (("restricted", "within Nabta's categories"), ("unrestricted", "any of its 102 classes")):
            add(
                f"| Published IP102 ResNet-50 (Wu et al., 2019), {scope} | – "
                f"| {official[reading]['macro_f1']:.3f} | {pct(official[reading]['accuracy'])} |"
            )
    else:
        add("| Published IP102 ResNet-50 (Wu et al., 2019) | – | – | not evaluated (weights unavailable) |")
    add("")

    # The charter's KPI (§8): the trained model improves on the initial baseline's macro F1.
    baselines = []
    if official:
        baselines.append(("the published IP102 ResNet-50 within Nabta's categories", official["restricted"]["macro_f1"]))
    if baseline and baseline is not chosen:
        baselines.append(("the in-house ResNet-50", baseline["test"]["macro_f1"]))
    if baselines:
        score = chosen["test"]["macro_f1"]
        met = all(score > other for _, other in baselines)
        against = "; ".join(f"{name} {other:.3f} ({score - other:+.3f})" for name, other in baselines)
        add(
            f"**Charter KPI (§8), {'met' if met else 'not met'}:** the chosen model's test macro F1 is "
            f"{score:.3f}. Baselines on the same test split: {against}.\n"
        )
    if official:
        add(
            "The published model's preprocessing isn't documented, so the better of two standard choices on a "
            f"validation sample was used ({official['preprocessing']}). Unrestricted, it named a class outside "
            f"Nabta's categories for {pct(official['unrestricted_outside_categories'])} of the test photos.\n"
        )

    add(f"## Per category ({LABELS[summary['chosen']]}, test split)\n")
    add("| Category | Precision | Recall | F1 | Test images |")
    add("| --- | ---: | ---: | ---: | ---: |")
    for name in names:
        c = chosen["test"]["per_class"][name]
        add(f"| {name} | {c['precision']:.3f} | {c['recall']:.3f} | {c['f1']:.3f} | {c['support']} |")
    add("")

    add("## Confusion matrix\n")
    image = config.REPORTS_DIR / "confusion_matrix.png"
    confusion_image(chosen["test"]["confusion"], names, f"{LABELS[summary['chosen']]}: test split", image)
    add("Rows are the true category and columns the prediction; colour shows the share of each row.\n")
    add("![Confusion matrix](confusion_matrix.png)\n")
    add("| True \\ predicted | " + " | ".join(names) + " |")
    add("| --- | " + " | ".join("---:" for _ in names) + " |")
    for name, row in zip(names, chosen["test"]["confusion"]):
        add(f"| {name} | " + " | ".join(str(v) for v in row) + " |")
    add("")

    add('## Uncertainty: when Nabta says "unclear"\n')
    validation, test = chosen["uncertainty"]["validation"], chosen["uncertainty"]["test"]
    before, after = chosen["calibration"]["test_ece_before"], chosen["calibration"]["test_ece_after"]
    add(
        f"**The rule.** A photo is shown as identified only when it is *familiar* (its features have a cosine "
        f"similarity of at least {chosen['familiarity_threshold']:.3f} with at least one training photo) **and** "
        f"its top category has a probability of at least {chosen['min_confidence']:.0%}. Anything else is "
        "\"unclear\", with the closest matches and the specialist route. The 50% floor was fixed in advance "
        "(an identified result must be more likely than not); the familiarity cut-off was chosen on validation "
        "to balance accepting supported insects against rejecting the tuning group of unsupported insects "
        f"({counts['unsupported_tuning_classes']} IP102 classes).\n"
    )
    add("| With Nabta's rule | Validation | Test |")
    add("| --- | ---: | ---: |")
    add(f"| Supported insects accepted | {pct(validation['supported_accepted'])} | {pct(test['supported_accepted'])} |")
    add(
        f"| Accuracy of accepted results | {pct(validation['accuracy_when_accepted'])} "
        f"| {pct(test['accuracy_when_accepted'])} |"
    )
    add(
        f"| Unsupported insects rejected | {pct(validation['unsupported_rejected'])} (tuning group) "
        f"| {pct(test['unsupported_rejected'])} (held-out group) |\n"
    )
    add(
        f"The held-out group ({counts['unsupported_held_out_classes']} other IP102 classes, "
        f"{counts['unsupported_held_out']} test images) was never seen while choosing the rule, so its "
        "rejection rate is the honest estimate for insect types Nabta doesn't know (charter R03).\n"
    )
    add(
        "**Why familiarity.** Three scores were compared for telling supported from unsupported insects; "
        "the nearest-training-photo similarity was clearly best on validation (AUROC, 0.5 = chance):\n"
    )
    add("| Score | Validation AUROC | Test AUROC |")
    add("| --- | ---: | ---: |")
    for name, score in chosen["open_set_scores"].items():
        add(f"| {name} | {score['validation_auroc']:.3f} | {score['test_auroc']:.3f} |")
    only_val, only_test = chosen["confidence_only"]["validation"], chosen["confidence_only"]["test"]
    add(
        f"\nWith confidence alone (best threshold {only_val['threshold']:.3f} on validation), the test split "
        f"would accept {pct(only_test['supported_accepted'])} of supported insects and reject "
        f"{pct(only_test['unsupported_rejected'])} of the held-out group, against "
        f"{pct(test['supported_accepted'])} and {pct(test['unsupported_rejected'])} with Nabta's rule.\n"
    )
    add(
        f"**Calibration.** Temperature scaling (T = {chosen['temperature']:.3f}, fitted on validation) gives a "
        f"test expected calibration error of {pct(after)}, against {pct(before)} without it"
        + (". " if after < before else " (no improvement on test; both are low). ")
        + "Shown confidences can be read as probabilities.\n"
    )
    if summary["unsuitable_photos"]:
        add("Unsuitable photos (test photos made unusable on purpose):\n")
        add("| Photos | Images | Shown as unclear |")
        add("| --- | ---: | ---: |")
        for name, outcome in summary["unsuitable_photos"].items():
            add(f"| {name.capitalize()} | {outcome['images']} | {pct(outcome['rejected'])} |")
        add("")

    add("## Data\n")
    add("| Group | Images | Used for |")
    add("| --- | ---: | --- |")
    add(
        f"| Train | {counts['train']} (+{counts['train_augmented_views']} augmented views) "
        "| fitting the head |"
    )
    add(f"| Validation | {counts['validation']} | regularisation, temperature, the familiarity cut-off, model choice |")
    add(f"| Test | {counts['test']} | the results above |")
    add(
        f"| Unsupported, tuning group | {counts['unsupported_tuning']} "
        f"({counts['unsupported_tuning_classes']} classes) | choosing the familiarity cut-off |"
    )
    add(
        f"| Unsupported, held-out group | {counts['unsupported_held_out']} "
        f"({counts['unsupported_held_out_classes']} classes) | measuring rejection |"
    )
    add(f"\n{counts['duplicates_excluded']} validation and test images were excluded as near-duplicates of earlier splits.\n")

    add("## How the model was chosen\n")
    add(
        "Each backbone's head is a class-balanced logistic regression on unit-length features; its "
        "regularisation strength C was chosen on validation macro F1:\n"
    )
    strengths = list(next(iter(models.values()))["validation_macro_f1_by_strength"])
    add("| Backbone | " + " | ".join(f"C = {s}" for s in strengths) + " | Features |")
    add("| --- | " + " | ".join("---:" for _ in strengths) + " | ---: |")
    for name, result in models.items():
        scores = result["validation_macro_f1_by_strength"]
        add(f"| {LABELS[name]} | " + " | ".join(f"{scores[s]:.3f}" for s in strengths) + f" | {result['feature_dim']} |")
    add(
        "\nThe backbone with the higher validation macro F1 is chosen; on a tie the smaller model wins "
        "(charter §18: performance, then size and deployment needs).\n"
    )
    if summary["zero_shot"]:
        add("Zero-shot prompts: " + "; ".join(f"{k}: " + ", ".join(v) for k, v in summary["zero_shot"]["prompts"].items()) + "\n")

    add("## Limits\n")
    add(
        "- These are benchmark photos (IP102), not growers' own photos. Results on photos collected from "
        "growers will be reported separately (charter §8).\n"
        "- The audit found some label noise (drawings, damage-only photos, mixed life stages); see "
        "[label-check.md](label-check.md).\n"
        "- Rejection is measured on insects from IP102's other classes; insects from outside IP102 may "
        "behave differently.\n"
    )
    add("## Reproduce\n")
    add(
        "```\npython -m nabta_ml.prepare\npython -m nabta_ml.audit\n"
        "python -m nabta_ml.features --backbone bioclip\npython -m nabta_ml.features --backbone resnet50 --no-augment\n"
        "python -m nabta_ml.official  # needs resnet50_0.497.pkl, see ml/README.md\n"
        "python -m nabta_ml.train\npython -m nabta_ml.export\n```\n"
    )
    add(f"Seed {summary['seed']}; dataset {summary['dataset']['name']} from {summary['dataset']['obtained_from']}.")
    (config.REPORTS_DIR / "evaluation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    """Rewrites evaluation.md from evaluation.json, picking up the published baseline's results
    if nabta_ml.official ran after training:  python -m nabta_ml.report"""
    import json
    import sys

    sys.stdout.reconfigure(encoding="utf-8")
    path = config.REPORTS_DIR / "evaluation.json"
    summary = json.loads(path.read_text(encoding="utf-8"))
    official = config.REPORTS_DIR / "official_baseline.json"
    if official.is_file():
        summary["official_ip102_baseline"] = json.loads(official.read_text(encoding="utf-8"))
    path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    write_report(summary, [category["name"] for category in summary["categories"]])
    print(f"Wrote {config.REPORTS_DIR / 'evaluation.md'}")


if __name__ == "__main__":
    main()
